#!/usr/bin/env node

/**
 * Projects the phaser's boxes (`service/phaser-gun.ts`) into the hud's icon, `components/phaser-icon.gen.ts`.
 * `--png` also draws it off, armed and dead, to that file.
 * ```sh
 * gen-phaser-icon
 * gen-phaser-icon --png /tmp/phaser-icon.png
 * ```
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path/posix";
import { parseArgs } from "node:util";
import { Canvas, Path2D } from "skia-canvas";
import { type GunBox, gunBoxes, gunMuzzle } from "../../../packages/ui/world/src/service/phaser-gun.ts";
import { PROJECT_ROOT } from "../const.ts";

const { values: opts } = parseArgs({ options: { png: { type: "string" } } });

/** Degrees the view turns from side-on towards the muzzle, and looks down */
const [azimuth, elevation] = [(38 * Math.PI) / 180, (28 * Math.PI) / 180];
const [ca, sa, ce, se] = [Math.cos(azimuth), Math.sin(azimuth), Math.cos(elevation), Math.sin(elevation)];
/** The icon's size, the room kept round the gun, and how far right it sits to leave the beam room */
const [size, margin, shift] = [64, 6, -6];

/** The forearm's frame as forward, side and up */
const fsu = ([x, y, z]: number[]) => [-y, z, x] as const;
/** Screen `x` right and `y` down, and depth towards the eye */
const project = (p: number[]) => {
  const [f, s, u] = fsu(p);
  return { x: f * ca - s * sa, y: f * sa * se + s * ca * se - u * ce, depth: f * sa * ce + s * ca * ce + u * se };
};

type FaceKey = "top" | "side" | "end";
/** Each box's faces we see: its top, its side towards us, its front */
const faceCorners = (b: GunBox): [FaceKey, number[][]][] => {
  const [x0, y0, z0] = b.min;
  const [x1, y1, z1] = b.max;
  return [
    [
      "top",
      [
        [x1, y1, z0],
        [x1, y0, z0],
        [x1, y0, z1],
        [x1, y1, z1],
      ],
    ],
    [
      "side",
      [
        [x0, y1, z1],
        [x0, y0, z1],
        [x1, y0, z1],
        [x1, y1, z1],
      ],
    ],
    [
      "end",
      [
        [x0, y0, z1],
        [x0, y0, z0],
        [x1, y0, z0],
        [x1, y0, z1],
      ],
    ],
  ];
};
const inside = (p: number[], b: GunBox) => p.every((v, i) => v > b.min[i] + 1e-6 && v < b.max[i] - 1e-6);

/** Farthest first, each face bar those buried in another box */
const faces = [...gunBoxes]
  .sort((a, b) => project(centre(a)).depth - project(centre(b)).depth)
  .flatMap((box) =>
    faceCorners(box)
      .filter(([, corners]) => gunBoxes.some((other) => other !== box && inside(mean(corners), other)) === false)
      .map(([face, corners]) => ({ box, face, points: corners.map(project) })),
  );

// fitted to the icon, a little left of centre
const all = faces.flatMap((f) => f.points);
const [minX, maxX] = [Math.min(...all.map((p) => p.x)), Math.max(...all.map((p) => p.x))];
const [minY, maxY] = [Math.min(...all.map((p) => p.y)), Math.max(...all.map((p) => p.y))];
const scale = (size - 2 * margin) / Math.max(maxX - minX, maxY - minY);
const toIcon = ({ x, y }: { x: number; y: number }) => ({
  x: round((x - (minX + maxX) / 2) * scale + size / 2 + shift),
  y: round((y - (minY + maxY) / 2) * scale + size / 2),
});

const muzzle = toIcon(project(gunMuzzle));
/** The beam along the barrel to the icon's right edge */
const beamDir = { x: ca, y: sa * se };
const beamTo = { x: size - 2, y: round(muzzle.y + ((size - 2 - muzzle.x) * beamDir.y) / beamDir.x) };

const colors = { gun: "#6c7582", beam: "#ff8a5c", dead: "#3d7fd9", slot: "#2e353f" };
/** Lit from above, as the gun is */
const faceShade: Record<FaceKey, number> = { top: 1.32, side: 1, end: 0.74 };
const glowShade: Record<FaceKey, number> = { top: 1.15, side: 1, end: 0.85 };

/** A face's fill put away, drawn and deactivated */
const fillsOf = ({ kind, tone }: GunBox, face: FaceKey) => {
  const body = shade(colors.gun, tone * faceShade[face]);
  if (kind === "emitter")
    return { off: body, armed: shade(colors.beam, glowShade[face]), dead: shade(colors.dead, glowShade[face]) };
  if (kind === "strip") {
    const slot = shade(colors.slot, faceShade[face]);
    return { off: slot, armed: mix(slot, colors.beam, 0.55), dead: slot };
  }
  return { off: body, armed: body, dead: body };
};

const iconFaces = faces.map(({ box, face, points }) => ({
  d: `M${points
    .map((p) => toIcon(p))
    .map(({ x, y }) => `${x} ${y}`)
    .join(" ")}Z`,
  ...fillsOf(box, face),
}));

const out = join(PROJECT_ROOT, "packages/ui/world/src/components/phaser-icon.gen.ts");
writeFileSync(
  out,
  `// Generated by \`gen-phaser-icon\` from \`service/phaser-gun.ts\`: do not edit
/** The phaser's faces, farthest first, each with its fill put away, drawn and deactivated */
export const phaserIconFaces = ${JSON.stringify(iconFaces, null, 2)};

/** Where its beam leaves, and where it meets the icon's edge */
export const phaserIconBeam = ${JSON.stringify({ from: muzzle, to: beamTo })};
`,
);
execFileSync("npx", ["biome", "format", "--write", out], { cwd: PROJECT_ROOT, stdio: "ignore" });
console.log(`wrote ${out}`);

if (opts.png !== undefined) {
  const zoom = 8;
  const canvas = new Canvas(3 * size * zoom, size * zoom);
  const ctx = canvas.getContext("2d");
  ctx.fillStyle = "#1b1f26";
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  (["off", "armed", "dead"] as const).forEach((state, i) => {
    ctx.save();
    ctx.scale(zoom, zoom);
    ctx.translate(i * size, 0);
    ctx.strokeStyle = "#2b3038";
    ctx.lineWidth = 0.5;
    ctx.lineJoin = "round";
    for (const face of iconFaces) {
      const path = new Path2D(face.d);
      ctx.fillStyle = face[state];
      ctx.fill(path);
      ctx.stroke(path);
    }
    if (state === "armed") {
      ctx.strokeStyle = colors.beam;
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      ctx.moveTo(muzzle.x, muzzle.y);
      ctx.lineTo(beamTo.x, beamTo.y);
      ctx.stroke();
    }
    ctx.restore();
  });
  await canvas.toFile(opts.png);
  console.log(`wrote ${opts.png}`);
}

function centre(b: GunBox) {
  return b.min.map((v, i) => (v + b.max[i]) / 2);
}
function mean(points: number[][]) {
  return [0, 1, 2].map((i) => points.reduce((sum, p) => sum + p[i], 0) / points.length);
}
function round(v: number) {
  return Math.round(v * 10) / 10;
}
function rgb(hex: string) {
  return [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
}
function hexOf(c: number[]) {
  return `#${c
    .map((v) =>
      Math.round(Math.min(255, Math.max(0, v)))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}
function shade(hex: string, k: number) {
  return hexOf(rgb(hex).map((v) => v * k));
}
function mix(a: string, b: string, t: number) {
  const [ca, cb] = [rgb(a), rgb(b)];
  return hexOf(ca.map((v, i) => v + (cb[i] - v) * t));
}
